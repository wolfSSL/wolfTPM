/* Clock resumes from its NV checkpoint and becomes safe one checkpoint
 * interval later, unless the NV state kept it safe. */
static void FwClockRestoreSafe(FWTPM_CTX* ctx)
{
    ctx->clockUnsafeUntil = ctx->clockNvValue >
        ~(UINT64)0 - FWTPM_CLOCK_UPDATE_MS ? ~(UINT64)0 :
        ctx->clockNvValue + FWTPM_CLOCK_UPDATE_MS;
}

int FWTPM_Init(FWTPM_CTX* ctx)
{
    int rc;
    int rngInit = 0;
    int wcInit = 0;
    FWTPM_NV_HAL savedNvHal;
    struct FWTPM_CLOCK_HAL_S savedClockHal;
#ifndef FWTPM_NO_PP
    struct FWTPM_PP_HAL_S savedPpHal;
#endif
#ifdef WOLFTPM_FWTPM_TIS
    FWTPM_TIS_HAL savedTisHal;
#else
    FWTPM_IO_HAL savedIoHal;
#endif

    if (ctx == NULL) {
        return BAD_FUNC_ARG;
    }

    /* Save any pre-configured HALs before zeroing context */
    XMEMCPY(&savedNvHal, &ctx->nvHal, sizeof(savedNvHal));
    XMEMCPY(&savedClockHal, &ctx->clockHal, sizeof(savedClockHal));
#ifndef FWTPM_NO_PP
    XMEMCPY(&savedPpHal, &ctx->ppHal, sizeof(savedPpHal));
#endif
#ifdef WOLFTPM_FWTPM_TIS
    XMEMCPY(&savedTisHal, &ctx->tisHal, sizeof(savedTisHal));
#else
    XMEMCPY(&savedIoHal, &ctx->ioHal, sizeof(savedIoHal));
#endif

    XMEMSET(ctx, 0, sizeof(FWTPM_CTX));

    /* Restore HALs if they were set before init */
    if (savedNvHal.read != NULL) {
        XMEMCPY(&ctx->nvHal, &savedNvHal, sizeof(savedNvHal));
    }
    if (savedClockHal.get_ms != NULL) {
        XMEMCPY(&ctx->clockHal, &savedClockHal, sizeof(savedClockHal));
    }
#ifndef FWTPM_NO_PP
    if (savedPpHal.get_pp != NULL) {
        XMEMCPY(&ctx->ppHal, &savedPpHal, sizeof(savedPpHal));
    }
#endif
#ifdef WOLFTPM_FWTPM_TIS
    if (savedTisHal.init != NULL) {
        XMEMCPY(&ctx->tisHal, &savedTisHal, sizeof(savedTisHal));
    }
#else
    if (savedIoHal.wait != NULL) {
        XMEMCPY(&ctx->ioHal, &savedIoHal, sizeof(savedIoHal));
    }
#endif

#ifndef WOLFTPM_FWTPM_TIS
    /* Set default ports (socket transport only) */
    ctx->cmdPort = FWTPM_CMD_PORT;
    ctx->platPort = FWTPM_PLAT_PORT;
#endif

    /* Default to powered on - the server process being running means
     * the TPM is powered. Platform port can still toggle this. */
    ctx->powerOn = 1;

    /* Initialize wolfCrypt RNG */
    rc = wolfCrypt_Init();
    if (rc == 0) {
        wcInit = 1;
        rc = wc_InitRng(&ctx->rng);
        if (rc == 0) {
            rngInit = 1;
        }
    }

    /* timeEpoch is an opaque random nonce, not a wall-clock value. It is
     * authenticated into authorization tickets and regenerated by Clear. */
    if (rc == 0) {
        rc = wc_RNG_GenerateBlock(&ctx->rng, ctx->timeEpoch,
            sizeof(ctx->timeEpoch));
    }

#ifndef FWTPM_NO_CONTEXT
    /* Generate per-boot context protection key (volatile only) for
     * ContextSave/ContextLoad HMAC + AES-CFB session blob protection. */
    if (rc == 0) {
        rc = wc_RNG_GenerateBlock(&ctx->rng, ctx->ctxProtectKey,
            sizeof(ctx->ctxProtectKey));
        if (rc == 0) {
            ctx->ctxProtectKeyValid = 1;
        }
    }
#endif

    /* Initialize NV storage - loads existing state or creates fresh seeds */
#ifndef FWTPM_NO_NV
    if (rc == 0) {
        /* A compaction during the load cannot establish Clock safety. */
        ctx->clockUnsafeUntil = ~(UINT64)0;
        rc = FWTPM_NV_Init(ctx);
    }
#else
    /* No NV: generate ephemeral seeds (lost on reset) */
    if (rc == 0)
        rc = wc_RNG_GenerateBlock(&ctx->rng, ctx->ownerSeed, FWTPM_SEED_SIZE);
    if (rc == 0)
        rc = wc_RNG_GenerateBlock(&ctx->rng, ctx->endorsementSeed,
            FWTPM_SEED_SIZE);
    if (rc == 0)
        rc = wc_RNG_GenerateBlock(&ctx->rng, ctx->platformSeed,
            FWTPM_SEED_SIZE);
    if (rc == 0)
        rc = wc_RNG_GenerateBlock(&ctx->rng, ctx->nullSeed,
            FWTPM_SEED_SIZE);
    if (rc == 0) {
        ctx->pcrAllocatedBanks = FWTPM_PCR_ALLOC_DEFAULT;
        ctx->endorsementProofVersion = 1;
        ctx->clockSafe = 1;
    }
#ifndef FWTPM_NO_DA
    if (rc == 0) {
        ctx->daMaxTries = FWTPM_DA_DEFAULT_MAX_TRIES;
        ctx->daRecoveryTime = FWTPM_DA_DEFAULT_RECOVERY;
        ctx->daLockoutRecovery = FWTPM_DA_DEFAULT_LOCKOUT_RECOVERY;
        ctx->orderly = 1;
    }
#endif
#endif

    /* The NV load keeps clockSafe only from a committed orderly marker.
     * Fresh state has reported no Clock yet, so it is safe. */
    if (rc == TPM_RC_SUCCESS) {
        ctx->clockNvValue = ctx->clockOffset;
        FwClockRestoreSafe(ctx);
    }

    if (rc != 0) {
        if (rngInit) {
            wc_FreeRng(&ctx->rng);
        }
        if (wcInit) {
            wolfCrypt_Cleanup();
        }
    }

    return rc;
}

int FWTPM_Cleanup(FWTPM_CTX* ctx)
{
    int rc;

    if (ctx == NULL) {
        return BAD_FUNC_ARG;
    }

    /* Save NV state before cleanup */
#ifndef FWTPM_NO_NV
    rc = FWTPM_NV_Save(ctx);
#else
    rc = TPM_RC_SUCCESS;
#endif

    /* Release transient objects, sessions, and hash/sign sequence slots first.
     * ForceZero alone would drop the live wc_HashAlg / Hmac contexts they own,
     * leaking their heap allocations under WOLFTPM_SMALL_STACK. */
    FWTPM_ResetCommandClient(ctx);

    wc_FreeRng(&ctx->rng);
    wolfCrypt_Cleanup();

    TPM2_ForceZero(ctx, sizeof(FWTPM_CTX));

    return rc;
}

const char* FWTPM_GetVersionString(void)
{
    return FWTPM_VERSION_STRING;
}

int FWTPM_Clock_SetHAL(FWTPM_CTX* ctx,
    UINT64 (*get_ms)(void* halCtx), void* halCtx)
{
    if (ctx == NULL || get_ms == NULL) {
        return BAD_FUNC_ARG;
    }
    ctx->clockHal.get_ms = get_ms;
    ctx->clockHal.ctx = halCtx;
    return 0;
}

UINT64 FWTPM_Clock_GetMs(FWTPM_CTX* ctx)
{
    UINT64 now = 0;
    if (ctx == NULL) {
        return 0;
    }
    /* If a clock HAL is registered, use it as the time base */
    if (ctx->clockHal.get_ms != NULL) {
        now = ctx->clockHal.get_ms(ctx->clockHal.ctx);
    }
    return now + ctx->clockOffset;
}

int FWTPM_Clock_PowerOn(FWTPM_CTX* ctx)
{
    UINT64 halNow = 0;
    if (ctx == NULL) {
        return BAD_FUNC_ARG;
    }
    if (ctx->clockHal.get_ms != NULL) {
        halNow = ctx->clockHal.get_ms(ctx->clockHal.ctx);
    }
    /* Powered-off time is not counted, whatever the HAL epoch. Unsigned
     * wrap is intended, as in ClockSet. */
    ctx->clockOffset = ctx->clockNvValue - halNow;
    ctx->timeBaseMs = halNow;
#ifndef FWTPM_NO_NV
    ctx->clockSafe = ctx->nvOrderly && ctx->clockSafe;
#else
    /* Without NV, Clock restarts from its boot value and can roll back. */
    ctx->clockSafe = 0;
#endif
    FwClockRestoreSafe(ctx);
    return TPM_RC_SUCCESS;
}

int FWTPM_Clock_Update(FWTPM_CTX* ctx)
{
    if (ctx == NULL) return BAD_FUNC_ARG;
#if !defined(FWTPM_NO_CLOCK) && !defined(FWTPM_NO_NV)
    if (ctx->wasStarted && ctx->powerOn) {
        UINT64 now = FWTPM_Clock_GetMs(ctx);
        if (now >= ctx->clockNvValue &&
                (now - ctx->clockNvValue >=
                    FWTPM_CLOCK_UPDATE_MS - FWTPM_CLOCK_POLL_MS ||
                 (!ctx->clockSafe && now >= ctx->clockUnsafeUntil))) {
            return FWTPM_NV_SaveClock(ctx);
        }
    }
#endif
    return TPM_RC_SUCCESS;
}

